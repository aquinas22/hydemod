"""Cut the full talk into normalized, positional mono Vorbis voice lines.

Usage: python3 tools/import_sam_voice.py build/voice-source/full_talk.webm
The full recording stays in build/voice-source; only short clips enter the mod jar.
Timing, subtitle and source metadata live in sam_voice_clips.json.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "src/main/resources/assets/hydemod"
MANIFEST = Path(__file__).with_name("sam_voice_clips.json")


def run(source: Path, manifest: Path = MANIFEST):
    data = json.loads(manifest.read_text())
    duration = float(subprocess.check_output([
        "ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", str(source)
    ], text=True))
    clips = data["clips"]
    # Validate every cut before replacing any assets.
    for name, clip in clips.items():
        start, end = clip["start"], clip["end"]
        if not (0 <= start < end <= duration) or end - start > 8:
            raise ValueError(f"Invalid voice cut {name}: {start}–{end}, source duration {duration}")
    out = ASSETS / "sounds/sam"
    out.mkdir(parents=True, exist_ok=True)
    sounds = json.loads((ASSETS / "sounds.json").read_text())
    lang = json.loads((ASSETS / "lang/en_us.json").read_text())
    entries = []
    for name, clip in clips.items():
        length = clip["end"] - clip["start"]
        filename = name.replace(".", "_")
        fade_out = max(0, length - 0.055)
        subprocess.run([
            "ffmpeg", "-y", "-v", "error", "-ss", str(clip["start"]), "-i", str(source),
            "-t", str(length), "-vn", "-ac", "1", "-ar", "44100", "-af",
            f"highpass=f=85,lowpass=f=10000,loudnorm=I=-18:TP=-2:LRA=7,afade=t=in:d=0.025,afade=t=out:st={fade_out}:d=0.055",
            "-c:a", "libvorbis", "-q:a", "5", str(out / f"{filename}.ogg")
        ], check=True)
        event = f"sam.voice.{name}"
        subtitle = f"subtitles.hydemod.{event}"
        sounds[event] = {"subtitle": subtitle, "sounds": [{"name": f"hydemod:sam/{filename}", "attenuation_distance": 32}]}
        lang[subtitle] = f"Sam Hyde: {clip['text']}"
        lang[f"boss.hydemod.sam_hyde.{name}"] = clip["text"]
        entries.append(f'            Map.entry("{name}", {math.ceil(length * 20) + 8})')
    (ASSETS / "sounds.json").write_text(json.dumps(sounds, indent=2) + "\n")
    (ASSETS / "lang/en_us.json").write_text(json.dumps(lang, indent=2, ensure_ascii=False) + "\n")
    java = ROOT / "src/main/java/com/hydemod/registry/SamVoiceLines.java"
    java.write_text('''package com.hydemod.registry;

import java.util.Map;

/** Generated by tools/import_sam_voice.py from the clip manifest. Durations prevent voice overlap. */
public final class SamVoiceLines {
    public static final Map<String, Integer> TICKS = Map.ofEntries(
''' + ",\n".join(entries) + ''');
    private SamVoiceLines() { }
}
''')
    credits = {k: v for k, v in data.items() if k != "clips"}
    credits.update({"source_duration_seconds": duration, "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                    "license": "CC BY 3.0 — original talk, documented by the linked source record",
                    "license_url": "https://creativecommons.org/licenses/by/3.0/",
                    "changes": "Short excerpts, mono conversion, filtering, loudness normalization and fades.",
                    "clips": clips})
    (ASSETS / "sounds/sam/credits.json").write_text(json.dumps(credits, indent=2) + "\n")
    print(f"Imported {len(clips)} voice clips from {duration:.1f}s of full talk audio.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--manifest", type=Path, default=MANIFEST)
    args = parser.parse_args()
    run(args.source.resolve(), args.manifest.resolve())
